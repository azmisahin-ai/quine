//! # quine-bench-simple
//!
//! Faz 1 için minimal benchmark: **Fibonacci**, **String Reverse**, **List Sum**.
//!
//! Her problem, LLM'in tamamlaması gereken tek bir `pub fn` imzası ve
//! JSON tabanlı test case'leri içerir. [`harness_source`] fonksiyonu, sandbox'a
//! verilecek `main.rs` kaynak kodunu üretir: çözücü fonksiyon çağrılır,
//! sonuç JSON olarak stdout'a yazılır ve beklenen değerle karşılaştırma
//! dışarıda (Evaluator'da) yapılır.

use quine_common::{Problem, TestCase};
use serde_json::json;

/// Basit benchmark koleksiyonu.
#[derive(Debug, Clone, Copy, Default)]
pub struct SimpleBenchmark;

impl SimpleBenchmark {
    /// Benchmark'taki tüm problemler.
    pub fn problems() -> Vec<Problem> {
        vec![fibonacci(), string_reverse(), list_sum()]
    }

    /// Verilen id ile tek problemi bulur.
    pub fn problem(id: &str) -> Option<Problem> {
        Self::problems().into_iter().find(|p| p.id == id)
    }
}

/// `fib-001`: n. Fibonacci sayısı (iteratif).
pub fn fibonacci() -> Problem {
    Problem {
        id: "fib-001".into(),
        title: "Fibonacci".into(),
        description: "n. Fibonacci sayısını döndüren `fibonacci` fonksiyonunu yaz. \
                      f(0)=0, f(1)=1, f(n)=f(n-1)+f(n-2). Taşma olmaması için u64 döndür."
            .into(),
        function_signature: "pub fn fibonacci(n: u32) -> u64 { todo!() }".into(),
        test_cases: vec![
            TestCase { input: json!(0), expected: json!(0) },
            TestCase { input: json!(1), expected: json!(1) },
            TestCase { input: json!(10), expected: json!(55) },
            TestCase { input: json!(20), expected: json!(6765) },
        ],
    }
}

/// `rev-002`: Bir string'i ters çevir (Unicode karakter güvenliğiyle).
pub fn string_reverse() -> Problem {
    Problem {
        id: "rev-002".into(),
        title: "String Reverse".into(),
        description: "Verilen string'i karakter bazında (grapheme değil, `chars`) ters çevirip \
                      yeni bir String olarak döndüren `reverse_string` fonksiyonunu yaz."
            .into(),
        function_signature: "pub fn reverse_string(s: &str) -> String { todo!() }".into(),
        test_cases: vec![
            TestCase { input: json!(""), expected: json!("") },
            TestCase { input: json!("abc"), expected: json!("cba") },
            TestCase { input: json!("quine"), expected: json!("eniuq") },
            TestCase { input: json!("ayşe"), expected: json!("eşya") },
        ],
    }
}

/// `sum-003`: Sayı listesinin toplamı.
pub fn list_sum() -> Problem {
    Problem {
        id: "sum-003".into(),
        title: "List Sum".into(),
        description: "`i64` değerlerinden oluşan bir slice'ın toplamını döndüren `list_sum` \
                      fonksiyonunu yaz. Negatif sayılar da gelebilir."
            .into(),
        function_signature: "pub fn list_sum(xs: &[i64]) -> i64 { todo!() }".into(),
        test_cases: vec![
            TestCase { input: json!([]), expected: json!(0) },
            TestCase { input: json!([1, 2, 3]), expected: json!(6) },
            TestCase { input: json!([-5, 5]), expected: json!(0) },
            TestCase { input: json!([1000000, 2000000, 3000000]), expected: json!(6000000) },
        ],
    }
}

/// Sandbox'a verilecek `main.rs` içeriğini üretir.
///
/// Üretilen dosya şunları içerir:
/// 1. LLM çözümünün yapıştırılacağı `solution` modülü,
/// 2. her test case için fonksiyonu çağıran ve sonucu JSON olarak basan `main`.
///
/// Beklenen değerler **kodun içine gömülmez** — runner (Evaluator) stdout'u
/// kendi beklenen değerleriyle karşılaştırır. Böylece LLM cevabı testleri
/// "ezberleyemez" (ampirik doğrulama ilkesi).
pub fn harness_source(problem_id: &str) -> Option<String> {
    let p = SimpleBenchmark::problem(problem_id)?;
    let call = match p.id.as_str() {
        "fib-001" => "solution::fibonacci(input as u32)",
        "rev-002" => "solution::reverse_string(&input)",
        "sum-003" => "solution::list_sum(&input)",
        _ => return None,
    };
    let input_type = match p.id.as_str() {
        "fib-001" => "serde_json::Value", // cast to u32 in call
        "rev-002" => "String",
        "sum-003" => "Vec<i64>",
        _ => return None,
    };
    Some(format!(
        r#"// AUTO-GENERATED by quine-bench-simple — DO NOT EDIT BY AGENT
mod solution {{
{solution_body}
}}

fn main() {{
    // Test girdileri stdin'den satır satır JSON olarak okunur.
    use std::io::Read;
    let mut buf = String::new();
    std::io::stdin().read_to_string(&mut buf).expect("stdin");
    let inputs: Vec<{input_type}> = serde_json::from_str(&buf).expect("parse inputs");
    for input in inputs {{
        let out = {{ {call} }};
        println!("{{}}", serde_json::to_string(&out).expect("serialize"));
    }}
}}
"#,
        solution_body = indent_llm_slot(),
        input_type = input_type,
        call = call,
    ))
}

/// LLM kodunun yerleşeceği yuva (`__QUINE_SOLUTION__` placeholder ile).
fn indent_llm_slot() -> String {
    "    // __QUINE_SOLUTION__\n".to_string()
}

/// Placeholder'ı gerçek LLM koduyla değiştirir. Kodu 4空格 girintiyle sarar.
pub fn inject_solution(harness: &str, llm_code: &str) -> String {
    let indented: String = llm_code
        .lines()
        .map(|l| format!("    {l}\n"))
        .collect();
    harness.replace("    // __QUINE_SOLUTION__\n", &indented)
}

/// Evaluator'ın stdout satırlarıyla karşılaştıracağı beklenen JSON dizisi.
pub fn expected_outputs(problem_id: &str) -> Option<Vec<String>> {
    let p = SimpleBenchmark::problem(problem_id)?;
    Some(
        p.test_cases
            .iter()
            .map(|t| t.expected.to_string())
            .collect(),
    )
}

/// Harness'in derlenebilmesi için gereken harici crate'ler.
pub fn harness_cargo_toml() -> String {
    "[package]\nname = \"quine-harness\"\nversion = \"0.0.0\"\nedition = \"2021\"\n\n\
     [dependencies]\nserde_json = \"1\"\n\n[[bin]]\nname = \"harness\"\npath = \"src/main.rs\"\n"
        .to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn benchmark_has_three_problems() {
        let ps = SimpleBenchmark::problems();
        assert_eq!(ps.len(), 3);
        let ids: Vec<&str> = ps.iter().map(|p| p.id.as_str()).collect();
        assert_eq!(ids, ["fib-001", "rev-002", "sum-003"]);
    }

    #[test]
    fn every_problem_has_tests_and_signature() {
        for p in SimpleBenchmark::problems() {
            assert!(!p.function_signature.is_empty());
            assert!(!p.test_cases.is_empty());
            assert!(p.to_llm_prompt().contains(&p.title));
        }
    }

    #[test]
    fn harness_contains_placeholder_for_all_problems() {
        for id in ["fib-001", "rev-002", "sum-003"] {
            let h = harness_source(id).expect("harness");
            assert!(h.contains("__QUINE_SOLUTION__"));
            assert!(h.contains("mod solution"));
        }
        assert!(harness_source("olmayan-id").is_none());
    }

    #[test]
    fn inject_solution_replaces_placeholder() {
        let h = harness_source("fib-001").unwrap();
        let code = "pub fn fibonacci(n: u32) -> u64 { n as u64 }";
        let filled = inject_solution(&h, code);
        assert!(filled.contains(code));
        assert!(!filled.contains("__QUINE_SOLUTION__"));
    }

    #[test]
    fn expected_outputs_match_test_cases() {
        let e = expected_outputs("fib-001").unwrap();
        assert_eq!(e, vec!["0", "1", "55", "6765"]);
    }

    #[test]
    fn string_reverse_expected_is_correct() {
        let p = string_reverse();
        let outs: Vec<_> = p.test_cases.iter().map(|t| t.expected.as_str()).collect();
        assert_eq!(outs, vec![Some(""), Some("cba"), Some("eniuq"), Some("eşya")]);
    }
}
