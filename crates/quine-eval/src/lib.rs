/// Çalıştırma ortamının süresi ve çıktı sınırları.
#[derive(Debug, Clone)]
pub struct SandboxLimits {
    /// Derleme dahil toplam süre aşımı.
    pub timeout: Duration,
    /// stdout/stderr için maksimum byte.
    pub max_output_bytes: usize,
}

impl Default for SandboxLimits {
    fn default() -> Self {
        Self {
            timeout: Duration::from_secs(60),
            max_output_bytes: 64 * 1024,
        }
    }
}

/// Bir çalıştırmanın ham çıktısı.
#[derive(Debug, Clone, Default)]
pub struct RunOutput {
    pub stdout: String,
    pub stderr: String,
    pub exit_code: Option<i32>,
    pub timed_out: bool,
    pub duration: Duration,
}

impl RunOutput {
    pub fn succeeded(&self) -> bool {
        self.exit_code == Some(0) && !self.timed_out
    }
}

/// Kod yazma → derleme → çalıştırma sorumluluğu (API_CONTRACTS).
///
/// `Box::pin` kullanıldığı için trait **dyn-uyumlu**dur: sandbox seçimi
/// çalışma zamanında (`sandbox_from_env`) yapılabilir.
pub trait Sandbox: Send + Sync {
    fn kind(&self) -> &'static str;

    /// `problem`'in harness'iyle birleştirilen `llm_code`'u derler ve
    /// stdin olarak test girdileriyle çalıştırır.
    fn run_solution<'a>(
        &'a self,
        problem: &'a Problem,
        llm_code: &'a str,
    ) -> std::pin::Pin<Box<dyn std::future::Future<Output = Result<RunOutput>> + Send + 'a>>;
}

/// Basit helper: async gövdeyi Pin<Box> içine sarar.
macro_rules! boxed_async {
    ($e:expr) => {
        Box::pin($e)
    };
}

