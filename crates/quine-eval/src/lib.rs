/// Faz 4: `docker run --network none --memory ... --cpus ...` ile tam izolasyon.
/// Docker bulunamazsa [`LocalProcessSandbox`]’a düşer.
#[derive(Debug, Clone)]
pub struct DockerSandbox {
    pub image: String,
    pub limits: SandboxLimits,
    pub cpus: String,
    pub memory: String,
}

impl Default for DockerSandbox {
    fn default() -> Self {
        Self {
            image: "rust:1-slim-bookworm".into(),
            limits: SandboxLimits::default(),
            cpus: "1.0".into(),
            memory: "512m".into(),
        }
    }
}

impl DockerSandbox {
    pub fn available() -> bool {
        std::process::Command::new("docker")
            .arg("version")
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .status()
            .map(|s| s.success())
            .unwrap_or(false)
    }
}

impl Sandbox for DockerSandbox {
    fn kind(&self) -> &'static str {
        "docker"
    }

    fn run_solution(
        &self,
        problem: &Problem,
        llm_code: &str,
    ) -> std::pin::Pin<Box<dyn std::future::Future<Output = Result<RunOutput>> + Send + '_>> {
        boxed_async!(self.run_solution_impl(problem, llm_code))
    }
}

impl DockerSandbox {
    async fn run_solution_impl(&self, problem: &Problem, llm_code: &str) -> Result<RunOutput> {
        if !DockerSandbox::available() {
            tracing::warn!("docker yok — LocalProcessSandbox'a düşülüyor");
            return LocalProcessSandbox::new(self.limits.clone())
                .run_solution_impl(problem, llm_code)
                .await;
        }
        let harness = build_harness_source(problem)?;
        let full_src = bench::inject_solution(&harness, llm_code);
        let dir = std::env::temp_dir().join(format!("quine-docker-{}", Uuid::new_v4()));
        std::fs::create_dir_all(&dir)?;
        std::fs::write(dir.join("main.rs"), &full_src)?;

        let started = Instant::now();
        let secs = self.limits.timeout.as_secs();
        let stdin_lines: String = problem
            .test_cases
            .iter()
            .map(|t| format!("{}\n", compact_json(&t.input)))
            .collect();

        let mut child = tokio::process::Command::new("docker")
            .args([
                "run",
                "--rm",
                "-i",
                "--network",
                "none",
                "--memory",
                &self.memory,
                "--cpus",
                &self.cpus,
                "-v",
            ])
            .arg(format!("{}:/work:ro", dir.display()))
            .arg("-w")
            .arg("/work")
            .arg(&self.image)
            .args([
                "sh",
                "-c",
                &format!(
                    "timeout {secs} sh -c 'rustc --edition 2021 -o /tmp/h main.rs && /tmp/h'"
                ),
            ])
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .context("docker çalıştırılamadı")?;

        if let Some(mut si) = child.stdin.take() {
            si.write_all(stdin_lines.as_bytes()).await.ok();
        }

        let run = tokio::time::timeout(
            self.limits.timeout + Duration::from_secs(10),
            child.wait_with_output(),
        )
        .await;
        let mut output = RunOutput::default();
        match run {
            Ok(o) => {
                let o = o.context("docker süreci beklenemedi")?;
                output.stdout = truncate(&String::from_utf8_lossy(&o.stdout), self.limits.max_output_bytes);
                output.stderr = truncate(&String::from_utf8_lossy(&o.stderr), self.limits.max_output_bytes);
                output.exit_code = o.status.code();
            }
            Err(_) => output.timed_out = true,
        }
        output.duration = started.elapsed();
        cleanup(&dir);
        Ok(output)
    }
}

/// Hangi sandbox'ın kullanılacağını belirler (`QUINE_SANDBOX=local|docker`).
pub fn sandbox_from_env() -> Box<dyn Sandbox> {
    match std::env::var("QUINE_SANDBOX").unwrap_or_default().as_str() {
        "docker" => Box::new(DockerSandbox::default()),
        _ => Box::new(LocalProcessSandbox::default()),
    }
}

