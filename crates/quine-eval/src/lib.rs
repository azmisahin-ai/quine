/// Temp dizin içinde `rustc --edition 2021` ile derleyip süre aşımlı çalıştırır.
#[derive(Debug, Clone, Default)]
pub struct LocalProcessSandbox {
    pub limits: SandboxLimits,
}

impl LocalProcessSandbox {
    pub fn new(limits: SandboxLimits) -> Self {
        Self { limits }
    }

    fn workdir(&self) -> Result<PathBuf> {
        // Harness serde_json'a bağımlı; offline derlemede path bulmak riskli
        // olduğundan harness'i **bağımlılıksız** tutuyoruz (bkz. build_harness_source).
        let dir = std::env::temp_dir().join(format!("quine-sandbox-{}", Uuid::new_v4()));
        std::fs::create_dir_all(&dir).context("sandbox temp dizini oluşturulamadı")?;
        Ok(dir)
    }
}

/// Test girdilerini ve beklenenleri koda gömmeyen, **bağımlılıksız** harness üretir:
/// girdiler satır-satır stdin'den okunur (mini JSON), sonuçlar satır-satır stdout'a yazılır.
/// Beklenen değerler harness içinde BULUNMAZ — karşılaştırma Evaluator'da yapılır
/// (ampirik doğrulama ilkesi: LLM test çıktılarına erişemez).
fn build_harness_source(problem: &Problem) -> Result<String> {
    // quine-bench-simple şablonu placeholder içeriyor mu diye doğrulanır.
    let _ = bench::harness_source(&problem.id)
        .ok_or_else(|| anyhow!("bilinmeyen problem id: {}", problem.id))?;

    let (typed, parse_fn, call) = match problem.id.as_str() {
        "fib-001" => ("u64", "parse_u64", "solution::fibonacci(input as u32)"),
        "rev-002" => ("String", "parse_string", "json_str(&solution::reverse_string(&input))"),
        "sum-003" => ("Vec<i64>", "parse_i64_array", "solution::list_sum(&input)"),
        _ => return Err(anyhow!("bilinmeyen problem id: {}", problem.id)),
    };

    Ok(format!(
        r#"// AUTO-GENERATED by quine-eval — DO NOT EDIT BY AGENT
#![allow(dead_code)]
mod solution {{
{slot}
}}

// ---- std-only mini JSON helpers (no external crates) ----
fn json_escape(s: &str) -> String {{
    let mut o = String::new();
    for c in s.chars() {{
        match c {{
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            '\r' => o.push_str("\\r"),
            '\t' => o.push_str("\\t"),
            c => o.push(c),
        }}
    }}
    o
}}
fn json_str(s: &str) -> String {{ format!("\"{{}}\"", json_escape(s)) }}

fn parse_u64(line: &str) -> u64 {{ line.trim().parse().expect("u64 line") }}

fn parse_string(line: &str) -> String {{
    let t = line.trim();
    let inner = t.trim_start_matches('"').trim_end_matches('"');
    let mut o = String::new();
    let mut it = inner.chars();
    while let Some(c) = it.next() {{
        if c == '\\' {{
            match it.next() {{
                Some('"') => o.push('"'),
                Some('\\') => o.push('\\'),
                Some('n') => o.push('\n'),
                Some(other) => o.push(other),
                None => break,
            }}
        }} else {{
            o.push(c);
        }}
    }}
    o
}}

fn parse_i64_array(line: &str) -> Vec<i64> {{
    let t = line.trim().trim_start_matches('[').trim_end_matches(']');
    if t.trim().is_empty() {{ return vec![]; }}
    t.split(',').map(|x| x.trim().parse::<i64>().expect("i64 item")).collect()
}}

fn main() {{
    use std::io::{{BufRead, Write}};
    let stdin = std::io::stdin();
    let stdout = std::io::stdout();
    let mut out = stdout.lock();
    for line in stdin.lock().lines() {{
        let line = line.expect("read stdin line");
        if line.trim().is_empty() {{ continue; }}
        let input: {typed} = {parse_fn}(&line);
        let result = {{ {call} }};
        writeln!(out, "{{}}", result).expect("write stdout");
    }}
}}
"#,
        slot = "    // __QUINE_SOLUTION__",
        typed = typed,
        parse_fn = parse_fn,
        call = call,
    ))
}

impl Sandbox for LocalProcessSandbox {
    fn kind(&self) -> &'static str {
        "local"
    }

    fn run_solution(
        &self,
        problem: &Problem,
        llm_code: &str,
    ) -> std::pin::Pin<Box<dyn std::future::Future<Output = Result<RunOutput>> + Send + '_>> {
        boxed_async!(self.run_solution_impl(problem, llm_code))
    }
}

impl LocalProcessSandbox {
    async fn run_solution_impl(&self, problem: &Problem, llm_code: &str) -> Result<RunOutput> {
        let harness = build_harness_source(problem)?;
        let full_src = bench::inject_solution(&harness, llm_code);

        let dir = self.workdir()?;
        let src_path = dir.join("main.rs");
        let bin_path = dir.join("harness");
        std::fs::write(&src_path, &full_src).context("kaynak kod yazılamadı")?;

        let started = Instant::now();

        // 1) Derle (rustc, offline; hızlı döngü için optimizasyon kapalı).
        let compile = tokio::time::timeout(
            self.limits.timeout,
            tokio::process::Command::new(rustc_bin())
                .arg("--edition")
                .arg("2021")
                .arg("-C")
                .arg("opt-level=0")
                .arg("-o")
                .arg(&bin_path)
                .arg(&src_path)
                .stdout(Stdio::piped())
                .stderr(Stdio::piped())
                .output(),
        )
        .await;

        let mut output = RunOutput::default();

        let compile = match compile {
            Ok(c) => c.context("rustc başlatılamadı (PATH üzerinde olmalı)")?,
            Err(_) => {
                output.timed_out = true;
                output.duration = started.elapsed();
                cleanup(&dir);
                return Ok(output);
            }
        };

        if !compile.status.success() {
            output.stderr = truncate(
                &String::from_utf8_lossy(&compile.stderr),
                self.limits.max_output_bytes,
            );
            output.exit_code = compile.status.code();
            output.duration = started.elapsed();
            cleanup(&dir);
            return Ok(output); // derleme hatası → score 0
        }

        // 2) Çalıştır: test girdilerini stdin'e yaz, stdout/stderr yakala.
        let stdin_lines: String = problem
            .test_cases
            .iter()
            .map(|t| format!("{}\n", compact_json(&t.input)))
            .collect();

        let mut child = tokio::process::Command::new(&bin_path)
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .context("harness çalıştırılamadı")?;

        if let Some(mut si) = child.stdin.take() {
            si.write_all(stdin_lines.as_bytes()).await.ok();
        }

        let run = tokio::time::timeout(self.limits.timeout, child.wait_with_output()).await;

        match run {
            Ok(o) => {
                let o = o.context("harness süreci beklenemedi")?;
                output.stdout = truncate(
                    &String::from_utf8_lossy(&o.stdout),
                    self.limits.max_output_bytes,
                );
                output.stderr = truncate(
                    &String::from_utf8_lossy(&o.stderr),
                    self.limits.max_output_bytes,
                );
                output.exit_code = o.status.code();
            }
            Err(_) => {
                output.timed_out = true;
            }
        }

        output.duration = started.elapsed();
        cleanup(&dir);
        Ok(output)
    }
}

fn rustc_bin() -> &'static str {
    "rustc"
}

fn cleanup(dir: &Path) {
    let _ = std::fs::remove_dir_all(dir);
}

fn truncate(s: &str, max: usize) -> String {
    if s.len() <= max {
        s.to_string()
    } else {
        let mut end = max;
        while !s.is_char_boundary(end) {
            end -= 1;
        }
        format!("{}…[truncated]", &s[..end])
    }
}

/// Test girdisini sandbox'ın mini-parser'ının beklediği tek satırlık forma çevirir.
fn compact_json(v: &serde_json::Value) -> String {
    match v {
        serde_json::Value::String(s) => json_quote(s),
        serde_json::Value::Array(items) => {
            let parts: Vec<String> = items.iter().map(|i| i.as_i64().unwrap_or(0).to_string()).collect();
            format!("[{}]", parts.join(","))
        }
        other => other.to_string(),
    }
}

fn json_quote(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

