/// LLM kodunu Guardian'dan geçirir, sandbox'ta çalıştırır ve puanlar.
pub struct Evaluator {
    sandbox: Box<dyn Sandbox>,
    guardian: DiffAnalyzer,
    audit: Option<AuditLog>,
}

impl Evaluator {
    pub fn new(sandbox: Box<dyn Sandbox>) -> Self {
        Self {
            sandbox,
            guardian: DiffAnalyzer::default(),
            audit: None,
        }
    }

    pub fn with_audit(mut self, audit: AuditLog) -> Self {
        self.audit = Some(audit);
        self
    }

    /// Faz 1 kabul kriteri: evaluate → EvaluationResult { success, score }.
    pub async fn evaluate(
        &self,
        agent_id: Uuid,
        problem: &Problem,
        llm_code: &str,
    ) -> EvaluationResult {
        // 1) Guardian kapısı: tehlikeli kod sandbox'a hiç gitmez.
        if let Err(violation) = self.guardian.analyze(llm_code) {
            self.audit(AuditDecision::Blocked, agent_id, &violation.to_string());
            return EvaluationResult {
                problem_id: problem.id.clone(),
                agent_id,
                success: false,
                score: 0.0,
                stdout: String::new(),
                stderr: format!("GUARDIAN BLOCKED: {violation}"),
                duration_ms: 0,
                tests_passed: 0,
                tests_total: problem.test_cases.len(),
                evaluated_at: Utc::now(),
            };
        }
        self.audit(
            AuditDecision::Allowed,
            agent_id,
            "code passed guardian scan",
        );

        // 2) Sandbox'ta derle & çalıştır.
        let run = match self.sandbox.run_solution(problem, llm_code).await {
            Ok(r) => r,
            Err(e) => {
                return EvaluationResult {
                    problem_id: problem.id.clone(),
                    agent_id,
                    success: false,
                    score: 0.0,
                    stdout: String::new(),
                    stderr: format!("SANDBOX ERROR: {e:#}"),
                    duration_ms: 0,
                    tests_passed: 0,
                    tests_total: problem.test_cases.len(),
                    evaluated_at: Utc::now(),
                }
            }
        };

        // 3) Satır satır karşılaştır.
        // Beklenen çıktılar problem tanımından türetilir (gömülü sete bağımlı değil).
        let expected: Vec<String> = problem
            .test_cases
            .iter()
            .map(|t| t.expected.to_string())
            .collect();
        let got_lines: Vec<&str> = run.stdout.lines().collect();
        let mut passed = 0usize;
        let mut mismatches: Vec<String> = Vec::new();
        for (i, (exp, got)) in expected.iter().zip(got_lines.iter()).enumerate() {
            if normalize(exp) == normalize(got) {
                passed += 1;
            } else {
                let input = problem
                    .test_cases
                    .get(i)
                    .map(|t| t.input.to_string())
                    .unwrap_or_else(|| "?".into());
                mismatches.push(format!("girdi {input}: beklenen {exp}, alınan {got}"));
            }
        }
        // Beklenen sayıda satır gelmediyse (panik/erken çıkış) bunu da bildir;
        // aksi halde LLM başarısızlığın nedenini göremez.
        if got_lines.len() < expected.len() {
            mismatches.push(format!(
                "yalnızca {} / {} test çıktısı üretildi (panik veya erken çıkış)",
                got_lines.len(),
                expected.len()
            ));
        }
        let total = problem.test_cases.len();
        let score = if total == 0 {
            0.0
        } else {
            (passed as f64 / total as f64) * 100.0
        };

        let succeeded = run.succeeded();
        let stderr = if mismatches.is_empty() {
            run.stderr
        } else {
            let diag = mismatches
                .iter()
                .take(6)
                .map(|m| format!("  - {m}"))
                .collect::<Vec<_>>()
                .join("\n");
            if run.stderr.trim().is_empty() {
                format!("Başarısız testler:\n{diag}")
            } else {
                format!("{}\nBaşarısız testler:\n{diag}", run.stderr.trim_end())
            }
        };

        EvaluationResult {
            problem_id: problem.id.clone(),
            agent_id,
            success: passed == total && total > 0 && succeeded,
            score,
            stdout: run.stdout,
            stderr,
            duration_ms: run.duration.as_millis() as u64,
            tests_passed: passed,
            tests_total: total,
            evaluated_at: Utc::now(),
        }
    }

    fn audit(&self, decision: AuditDecision, agent_id: Uuid, detail: &str) {
        if let Some(log) = &self.audit {
            let _ = log.record(decision, Some(&agent_id.to_string()), detail);
        }
    }
}

/// JSON sayısal biçim farklarını yok eden normalize (örn. `55` vs `55\n`).
fn normalize(s: &str) -> String {
    s.trim().trim_matches('"').to_string()
}

#[cfg(test)]
mod tests {
    use super::*;
    use quine_bench_simple::SimpleBenchmark;
    use quine_common::TestCase;

    #[test]
    fn sandbox_from_kind_defaults_to_local() {
        // Boş/`local` → yerel sandbox; sessiz docker denemesi yok.
        assert_eq!(sandbox_from_kind("").unwrap().kind(), "local");
        assert_eq!(sandbox_from_kind("local").unwrap().kind(), "local");
        assert_eq!(sandbox_from_kind("bilinmeyen").unwrap().kind(), "local");
    }

    #[test]
    fn sandbox_from_kind_docker_fails_closed_without_docker() {
        // Güvenlik regresyonu: docker erişilemiyorsa hata dönmeli, yerel
        // sandbox'a sessizce düşmemeli.
        if DockerSandbox::available() {
            assert_eq!(sandbox_from_kind("docker").unwrap().kind(), "docker");
        } else {
            assert!(
                sandbox_from_kind("docker").is_err(),
                "docker erişilemezken sessizce local'e düşülmemeli"
            );
        }
    }

    #[test]
    fn compact_json_formats_inputs() {
        assert_eq!(compact_json(&serde_json::json!(10)), "10");
        assert_eq!(compact_json(&serde_json::json!("abc")), "\"abc\"");
        assert_eq!(compact_json(&serde_json::json!([1, 2, 3])), "[1,2,3]");
        assert_eq!(compact_json(&serde_json::json!([])), "[]");
    }

    #[test]
    fn normalize_handles_quotes_and_ws() {
        assert_eq!(normalize(" \"cba\" "), "cba");
        assert_eq!(normalize("55\n"), "55");
    }

    #[test]
    fn harness_builds_for_every_problem() {
        for p in SimpleBenchmark::problems() {
            let h = build_harness_source(&p).expect("harness");
            assert!(h.contains("__QUINE_SOLUTION__"));
            assert!(h.contains("mod solution"));
        }
    }

    #[test]
    fn parse_signature_extracts_name_args_and_return() {
        let (name, args, ret) =
            parse_signature("pub fn list_sum(xs: &[i64]) -> i64 { todo!() }").unwrap();
        assert_eq!(name, "list_sum");
        assert_eq!(args, vec![("xs".to_string(), "&[i64]".to_string())]);
        assert_eq!(ret, "i64");
    }

    #[test]
    fn parse_signature_handles_multiple_args() {
        let (name, args, ret) =
            parse_signature("pub fn clamp(v: i64, lo: i64, hi: i64) -> i64 { todo!() }").unwrap();
        assert_eq!(name, "clamp");
        assert_eq!(args.len(), 3);
        assert_eq!(ret, "i64");
    }

    #[test]
    fn parse_signature_rejects_non_signatures() {
        assert!(parse_signature("fn gizli() -> i64 { 0 }").is_none());
        assert!(parse_signature("pub fn no_return() { }").is_none());
    }

    #[test]
    fn generic_harness_works_for_external_problem() {
        let p = Problem {
            id: "ext-double".into(),
            title: "Double".into(),
            description: "Sayıyı ikiyle çarp.".into(),
            function_signature: "pub fn double(x: i64) -> i64 { todo!() }".into(),
            test_cases: vec![TestCase {
                input: serde_json::json!(21),
                expected: serde_json::json!(42),
            }],
        };
        let h = build_harness_source(&p).expect("dış problem için harness üretilmeli");
        assert!(h.contains("solution::double("));
        assert!(h.contains("__QUINE_SOLUTION__"));
    }

    #[test]
    fn multi_arg_inputs_become_typed_literals() {
        let p = Problem {
            id: "ext-gcd".into(),
            title: "GCD".into(),
            description: "iki argümanlı".into(),
            function_signature: "pub fn gcd(a: i64, b: i64) -> i64 { todo!() }".into(),
            test_cases: vec![TestCase {
                input: serde_json::json!([12, 18]),
                expected: serde_json::json!(6),
            }],
        };
        let h = build_harness_source(&p).expect("çok argümanlı harness");
        assert!(h.contains("solution::gcd(12i64, 18i64)"));
    }

    #[test]
    fn string_literals_are_escaped() {
        assert_eq!(rust_string_literal("al\"o\n"), "\"al\\\"o\\n\"");
    }

    #[test]
    fn vec_literal_is_emitted_for_slice_arg() {
        let p = Problem {
            id: "ext-run".into(),
            title: "Run".into(),
            description: "dizi".into(),
            function_signature: "pub fn longest_run(xs: &[i64]) -> usize { todo!() }".into(),
            test_cases: vec![TestCase {
                input: serde_json::json!([1, 1, 2]),
                expected: serde_json::json!(2),
            }],
        };
        let h = build_harness_source(&p).expect("dizi harness");
        assert!(h.contains("solution::longest_run(&vec![1, 1, 2])"));
    }

    #[test]
    fn multi_arg_arity_mismatch_is_rejected() {
        let p = Problem {
            id: "ext-bad".into(),
            title: "Bad".into(),
            description: "eksik argüman".into(),
            function_signature: "pub fn gcd(a: i64, b: i64) -> i64 { todo!() }".into(),
            test_cases: vec![TestCase {
                input: serde_json::json!([12]),
                expected: serde_json::json!(6),
            }],
        };
        assert!(build_harness_source(&p).is_err());
    }

    #[test]
    fn unsupported_type_is_rejected() {
        let p = Problem {
            id: "ext-map".into(),
            title: "Map".into(),
            description: "desteklenmeyen tip".into(),
            function_signature:
                "pub fn f(m: std::collections::HashMap<i64, i64>) -> i64 { todo!() }".into(),
            test_cases: vec![TestCase {
                input: serde_json::json!(1),
                expected: serde_json::json!(1),
            }],
        };
        assert!(build_harness_source(&p).is_err());
    }
}
