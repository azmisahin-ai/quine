//! # quine-eval
//!
//! Faz 1: LLM'den gelen kodu **geçici bir dizine yazıp derleyen ve çalıştıran**
//! [`Evaluator`] ile sandbox soyutlaması.
//!
//! İki sandbox stratejisi (bkz. docs/API_CONTRACTS.md):
//! * [`LocalProcessSandbox`] — `rustc` ile izole temp dizinde derleme + süre
//!   aşımlı çalıştırma (geliştirme & CI için; ağ yok, dosya sistemi temp ile sınırlı).
//! * [`DockerSandbox`] — Faz 4 hedefi: `--network none`, CPU/RAM limitleri.
//!   Docker yoksa otomatik olarak local'e düşer (`SandboxKind::auto`).

