/// Temp dizin içinde `rustc --edition 2021` ile derleyip süre aşımlı çalıştırır.
#[derive(Debug, Clone, Default)]
pub struct LocalProcessSandbox {
    pub limits: SandboxLimits,
}

impl LocalProcessSandbox {
    pub fn new(limits: SandboxLimits) -> Self {
        Self { limits }
    }

    fn workdir(&self) -> Result<PathBuf> {
        // Harness serde_json'a bağımlı; offline derlemede path bulmak riskli
        // olduğundan harness'i **bağımlılıksız** tutuyoruz (bkz. build_harness_source).
        let dir = std::env::temp_dir().join(format!("quine-sandbox-{}", Uuid::new_v4()));
        std::fs::create_dir_all(&dir).context("sandbox temp dizini oluşturulamadı")?;
        Ok(dir)
    }
}

/// Test girdilerini ve beklenenleri koda gömmeyen, **bağımlılıksız** harness üretir:
/// girdiler satır-satır stdin'den okunur (mini JSON), sonuçlar satır-satır stdout'a yazılır.
/// Beklenen değerler harness içinde BULUNMAZ — karşılaştırma Evaluator'da yapılır
/// (ampirik doğrulama ilkesi: LLM test çıktılarına erişemez).
fn build_harness_source(problem: &Problem) -> Result<String> {
    // Çözücü fonksiyonun imzası problem tanımındaki stub'tan türetilir; böylece
    // problem seti kod içine gömülü olmak zorunda değildir. Test girdileri,
    // harness'e **tipli Rust literal'leri** olarak gömülür: JSON'u çalışma
    // anında elle çözmek yerine bu yol hem çok argümanlı fonksiyonları hem de
    // tüm desteklenen tipleri doğru ele alır (harici crate yok).
    let (name, args, ret) = parse_signature(&problem.function_signature).ok_or_else(|| {
        anyhow!(
            "fonksiyon imzası çözümlenemedi: {}",
            problem.function_signature
        )
    })?;
    let out_fmt = out_expr(&ret).with_context(|| format!("dönüş tipi desteklenmiyor: {ret}"))?;

    let mut blocks = String::new();
    for (i, case) in problem.test_cases.iter().enumerate() {
        let lits = arg_literals(&args, &case.input)
            .with_context(|| format!("{i}. test girdisi çözümlenemedi"))?;
        blocks.push_str(&format!(
            "    {{ let result: {ret} = solution::{name}({call}); \
             writeln!(out, \"{{}}\", {out_fmt}).unwrap(); }}\n",
            ret = ret,
            name = name,
            call = lits.join(", "),
            out_fmt = out_fmt,
        ));
    }

    Ok(format!(
        r#"// AUTO-GENERATED by quine-eval — DO NOT EDIT BY AGENT
#![allow(dead_code)]
mod solution {{
{slot}
}}

// ---- std-only çıktı biçimlendirme yardımcıları (harici crate yok) ----
fn json_escape(s: &str) -> String {{
    let mut o = String::new();
    for c in s.chars() {{
        match c {{
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            '\r' => o.push_str("\\r"),
            '\t' => o.push_str("\\t"),
            c => o.push(c),
        }}
    }}
    o
}}
fn json_str(s: &str) -> String {{ format!("\"{{}}\"", json_escape(s)) }}
fn i64_vec_out(v: &[i64]) -> String {{
    let parts: Vec<String> = v.iter().map(|x| x.to_string()).collect();
    format!("[{{}}]", parts.join(","))
}}

fn main() {{
    use std::io::Write;
    let stdout = std::io::stdout();
    let mut out = stdout.lock();
{blocks}}}
"#,
        slot = "    // __QUINE_SOLUTION__",
        blocks = blocks,
    ))
}

/// Test girdisini imzadaki argüman tiplerine göre Rust literal'lerine çevirir.
///
/// Tek argümanlı fonksiyonda girdinin kendisi kullanılır; çok argümanlıda
/// girdinin `[a, b, ...]` dizisi olması beklenir.
fn arg_literals(args: &[(String, String)], input: &serde_json::Value) -> Result<Vec<String>> {
    if args.is_empty() {
        return Ok(Vec::new());
    }
    if args.len() == 1 {
        return Ok(vec![arg_literal(&args[0].1, input)?]);
    }
    let arr = input.as_array().ok_or_else(|| {
        anyhow!(
            "{args_len} argümanlı fonksiyon için dizi girdi bekleniyordu: {input}",
            args_len = args.len()
        )
    })?;
    if arr.len() != args.len() {
        bail!(
            "girdi dizisi {} elemanlı ama imzada {} argüman var: {input}",
            arr.len(),
            args.len()
        );
    }
    args.iter()
        .zip(arr.iter())
        .map(|((_, ty), v)| arg_literal(ty, v))
        .collect()
}

/// Tek bir değeri, verilen tipin Rust literal'ine çevirir.
fn arg_literal(ty: &str, value: &serde_json::Value) -> Result<String> {
    let ty = ty.trim();
    let (is_ref, base) = match ty.strip_prefix('&') {
        Some(rest) => (true, rest.trim()),
        None => (false, ty),
    };
    let lit = match base {
        "str" => rust_string_literal(
            value
                .as_str()
                .ok_or_else(|| anyhow!("string bekleniyordu: {value}"))?,
        ),
        "String" => format!(
            "{}.to_string()",
            rust_string_literal(
                value
                    .as_str()
                    .ok_or_else(|| anyhow!("string bekleniyordu: {value}"))?
            )
        ),
        "bool" => value
            .as_bool()
            .ok_or_else(|| anyhow!("bool bekleniyordu: {value}"))?
            .to_string(),
        "f32" | "f64" => float_literal(
            value
                .as_f64()
                .ok_or_else(|| anyhow!("sayı bekleniyordu: {value}"))?,
        ),
        "i8" | "i16" | "i32" | "i64" | "isize" | "u8" | "u16" | "u32" | "u64" | "usize" => {
            let n = value
                .as_i64()
                .ok_or_else(|| anyhow!("tam sayı bekleniyordu: {value}"))?;
            format!("{n}{base}")
        }
        "[i64]" | "Vec<i64>" => {
            let arr = value
                .as_array()
                .ok_or_else(|| anyhow!("dizi bekleniyordu: {value}"))?;
            let items = arr
                .iter()
                .map(|x| {
                    x.as_i64()
                        .map(|n| n.to_string())
                        .ok_or_else(|| anyhow!("i64 eleman bekleniyordu: {x}"))
                })
                .collect::<Result<Vec<_>>>()?;
            if is_ref {
                if items.is_empty() {
                    "&Vec::<i64>::new()".to_string()
                } else {
                    format!("&vec![{}]", items.join(", "))
                }
            } else if items.is_empty() {
                "Vec::<i64>::new()".to_string()
            } else {
                format!("vec![{}]", items.join(", "))
            }
        }
        other => bail!("desteklenmeyen argüman tipi: {other}"),
    };
    Ok(lit)
}

/// Rust string literal'i üretir (kaçış karakterleriyle).
fn rust_string_literal(s: &str) -> String {
    let mut o = String::with_capacity(s.len() + 2);
    o.push('"');
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            '\r' => o.push_str("\\r"),
            '\t' => o.push_str("\\t"),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

/// Ondalık nokta içermeyen sayıyı kayan nokta literal'ine çevirir (`2` → `2.0`).
fn float_literal(n: f64) -> String {
    let s = format!("{n}");
    if s.contains('.')
        || s.contains('e')
        || s.contains('E')
        || s.contains("inf")
        || s.contains("NaN")
    {
        s
    } else {
        format!("{s}.0")
    }
}

/// Dönüş tipi için stdout biçimlendirme ifadesi üretir.
fn out_expr(ret: &str) -> Result<String> {
    let ret = ret.trim();
    match ret {
        "String" => Ok("json_str(&result)".to_string()),
        "Vec<i64>" | "[i64]" => Ok("i64_vec_out(&result)".to_string()),
        "bool" => Ok("result.to_string()".to_string()),
        "f64" | "f32" | "u64" | "u32" | "u16" | "u8" | "usize" | "i64" | "i32" | "i16" | "i8"
        | "isize" => Ok("result.to_string()".to_string()),
        other => bail!("desteklenmeyen dönüş tipi: {other}"),
    }
}

/// Çözümlenmiş imza: (fonksiyon adı, [(argüman, tip)], dönüş tipi).
type Signature = (String, Vec<(String, String)>, String);

/// `pub fn ad(a: T, b: U) -> R { ... }` imzasını (ad, [(arg, tip)], dönüş tipi) olarak çözer.
fn parse_signature(sig: &str) -> Option<Signature> {
    let sig = sig.trim();
    let rest = sig.strip_prefix("pub fn ")?;
    let open = rest.find('(')?;
    let name = rest[..open].trim().to_string();
    let after_open = &rest[open + 1..];
    let close = matching_paren(after_open)?;
    let args_src = &after_open[..close];
    let after_args = after_open[close + 1..].trim_start();
    let ret_src = after_args.strip_prefix("->")?;
    let ret = ret_src
        .split('{')
        .next()?
        .trim()
        .trim_end_matches("where")
        .trim()
        .to_string();
    if ret.is_empty() {
        return None;
    }
    let mut args = Vec::new();
    if !args_src.trim().is_empty() {
        for part in split_top_level(args_src, ',') {
            let part = part.trim();
            if part.is_empty() {
                continue;
            }
            let colon = part.find(':')?;
            let aname = part[..colon].trim().to_string();
            let aty = part[colon + 1..].trim().to_string();
            args.push((aname, aty));
        }
    }
    Some((name, args, ret))
}

/// Açılış parantezinden sonraki içerikte eşleşen kapanış parantezinin indeksi.
fn matching_paren(s: &str) -> Option<usize> {
    let mut depth = 1usize;
    for (i, c) in s.char_indices() {
        match c {
            '(' => depth += 1,
            ')' => {
                depth -= 1;
                if depth == 0 {
                    return Some(i);
                }
            }
            _ => {}
        }
    }
    None
}

/// Parantez derinliğini koruyarak üst düzey ayırıcı ile böler.
fn split_top_level(s: &str, sep: char) -> Vec<String> {
    let mut parts = Vec::new();
    let mut depth = 0i32;
    let mut cur = String::new();
    for c in s.chars() {
        match c {
            '(' | '[' | '<' => {
                depth += 1;
                cur.push(c);
            }
            ')' | ']' | '>' => {
                depth -= 1;
                cur.push(c);
            }
            c if c == sep && depth == 0 => parts.push(std::mem::take(&mut cur)),
            _ => cur.push(c),
        }
    }
    parts.push(cur);
    parts
}

impl Sandbox for LocalProcessSandbox {
    fn kind(&self) -> &'static str {
        "local"
    }

    fn run_solution<'a>(
        &'a self,
        problem: &'a Problem,
        llm_code: &'a str,
    ) -> std::pin::Pin<Box<dyn std::future::Future<Output = Result<RunOutput>> + Send + 'a>> {
        boxed_async!(self.run_solution_impl(problem, llm_code))
    }
}

impl LocalProcessSandbox {
    async fn run_solution_impl(&self, problem: &Problem, llm_code: &str) -> Result<RunOutput> {
        let harness = build_harness_source(problem)?;
        let full_src = bench::inject_solution(&harness, llm_code);

        let dir = self.workdir()?;
        let src_path = dir.join("main.rs");
        let bin_path = dir.join("harness");
        std::fs::write(&src_path, &full_src).context("kaynak kod yazılamadı")?;

        let started = Instant::now();

        // 1) Derle (rustc, offline; hızlı döngü için optimizasyon kapalı).
        let compile = tokio::time::timeout(
            self.limits.timeout,
            tokio::process::Command::new(rustc_bin())
                .arg("--edition")
                .arg("2021")
                .arg("-C")
                .arg("opt-level=0")
                .arg("-o")
                .arg(&bin_path)
                .arg(&src_path)
                .stdout(Stdio::piped())
                .stderr(Stdio::piped())
                .output(),
        )
        .await;

        let mut output = RunOutput::default();

        let compile = match compile {
            Ok(c) => c.context("rustc başlatılamadı (PATH üzerinde olmalı)")?,
            Err(_) => {
                output.timed_out = true;
                output.duration = started.elapsed();
                cleanup(&dir);
                return Ok(output);
            }
        };

        if !compile.status.success() {
            output.stderr = truncate(
                &String::from_utf8_lossy(&compile.stderr),
                self.limits.max_output_bytes,
            );
            output.exit_code = compile.status.code();
            output.duration = started.elapsed();
            cleanup(&dir);
            return Ok(output); // derleme hatası → score 0
        }

        // 2) Çalıştır: test girdilerini stdin'e yaz, stdout/stderr yakala.
        let stdin_lines: String = problem
            .test_cases
            .iter()
            .map(|t| format!("{}\n", compact_json(&t.input)))
            .collect();

        let mut child = tokio::process::Command::new(&bin_path)
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .context("harness çalıştırılamadı")?;

        if let Some(mut si) = child.stdin.take() {
            si.write_all(stdin_lines.as_bytes()).await.ok();
        }

        let run = tokio::time::timeout(self.limits.timeout, child.wait_with_output()).await;

        match run {
            Ok(o) => {
                let o = o.context("harness süreci beklenemedi")?;
                output.stdout = truncate(
                    &String::from_utf8_lossy(&o.stdout),
                    self.limits.max_output_bytes,
                );
                output.stderr = truncate(
                    &String::from_utf8_lossy(&o.stderr),
                    self.limits.max_output_bytes,
                );
                output.exit_code = o.status.code();
            }
            Err(_) => {
                output.timed_out = true;
            }
        }

        output.duration = started.elapsed();
        cleanup(&dir);
        Ok(output)
    }
}

fn rustc_bin() -> &'static str {
    "rustc"
}

fn cleanup(dir: &Path) {
    let _ = std::fs::remove_dir_all(dir);
}

fn truncate(s: &str, max: usize) -> String {
    if s.len() <= max {
        s.to_string()
    } else {
        let mut end = max;
        while !s.is_char_boundary(end) {
            end -= 1;
        }
        format!("{}…[truncated]", &s[..end])
    }
}

/// Test girdisini sandbox'ın mini-parser'ının beklediği tek satırlık forma çevirir.
fn compact_json(v: &serde_json::Value) -> String {
    match v {
        serde_json::Value::String(s) => json_quote(s),
        serde_json::Value::Array(items) => {
            let parts: Vec<String> = items
                .iter()
                .map(|i| i.as_i64().unwrap_or(0).to_string())
                .collect();
            format!("[{}]", parts.join(","))
        }
        other => other.to_string(),
    }
}

fn json_quote(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

