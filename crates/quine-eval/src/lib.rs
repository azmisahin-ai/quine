//! # quine-eval
//!
//! Faz 1: LLM'den gelen kodu **geçici bir dizine yazıp derleyen ve çalıştıran**
//! [`Evaluator`] ile sandbox soyutlaması.
//!
//! İki sandbox stratejisi (bkz. docs/API_CONTRACTS.md):
//! * [`LocalProcessSandbox`] — `rustc` ile izole temp dizinde derleme + süre
//!   aşımlı çalıştırma (geliştirme & CI için; ağ yok, dosya sistemi temp ile sınırlı).
//! * [`DockerSandbox`] — Faz 4 hedefi: `--network none`, CPU/RAM limitleri.
//!   Docker yoksa otomatik olarak local'e düşer (`SandboxKind::auto`).

use anyhow::{anyhow, Context, Result};
use chrono::Utc;
use quine_bench_simple as bench;
use quine_common::{EvaluationResult, Problem};
use quine_guardian::{AuditDecision, AuditLog, DiffAnalyzer};
use std::path::{Path, PathBuf};
use std::process::Stdio;
use std::time::{Duration, Instant};
use tokio::io::AsyncWriteExt; // io-util feature ile ChildStdin'e write_all sağlar
use uuid::Uuid;

/// Çalıştırma ortamının süresi ve çıktı sınırları.
#[derive(Debug, Clone)]
pub struct SandboxLimits {
    /// Derleme dahil toplam süre aşımı.
    pub timeout: Duration,
    /// stdout/stderr için maksimum byte.
    pub max_output_bytes: usize,
}

impl Default for SandboxLimits {
    fn default() -> Self {
        Self {
            timeout: Duration::from_secs(60),
            max_output_bytes: 64 * 1024,
        }
    }
}

/// Bir çalıştırmanın ham çıktısı.
#[derive(Debug, Clone, Default)]
pub struct RunOutput {
    pub stdout: String,
    pub stderr: String,
    pub exit_code: Option<i32>,
    pub timed_out: bool,
    pub duration: Duration,
}

impl RunOutput {
    pub fn succeeded(&self) -> bool {
        self.exit_code == Some(0) && !self.timed_out
    }
}

/// Kod yazma → derleme → çalıştırma sorumluluğu (API_CONTRACTS).
///
/// `Box::pin` kullanıldığı için trait **dyn-uyumlu**dur: sandbox seçimi
/// çalışma zamanında (`sandbox_from_env`) yapılabilir.
pub trait Sandbox: Send + Sync {
    fn kind(&self) -> &'static str;

    /// `problem`'in harness'iyle birleştirilen `llm_code`'u derler ve
    /// stdin olarak test girdileriyle çalıştırır.
    fn run_solution(
        &self,
        problem: &Problem,
        llm_code: &str,
    ) -> std::pin::Pin<Box<dyn std::future::Future<Output = Result<RunOutput>> + Send + '_>>;
}

/// Basit helper: async gövdeyi Pin<Box> içine sarar.
macro_rules! boxed_async {
    ($e:expr) => {
        Box::pin($e)
    };
}

